const temporaryPaths: string[] = [];

function createTemporaryDirectory(prefix: string): string {
  const directory = path.join(os.tmpdir(), `milestack-update-${prefix}-${randomUUID()}`);
  mkdirSync(directory, { recursive: true });
  temporaryPaths.push(directory);
  return directory;
}

afterEach(() => {
  for (const target of temporaryPaths.splice(0)) {
    rmSync(target, { recursive: true, force: true });
  }
});

function outputCapture() {
  const stdout: string[] = [];
  const stderr: string[] = [];
  return {
    stdout,
    stderr,
    output: {
      writeStdout: (message: string) => stdout.push(message),
      writeStderr: (message: string) => stderr.push(message),
    },
  };
}

function writeFileAt(filePath: string, contents = "// fake CLI entry\n"): void {
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(filePath, contents, "utf8");
}

function createNpmGlobalEntry(): { prefix: string; entryPath: string } {
  const prefix = createTemporaryDirectory("prefix");
  const entryPath = path.join(prefix, "lib", "node_modules", "milestack", "dist", "index.js");
  writeFileAt(entryPath);
  return { prefix, entryPath };
}

function createSourceRepoEntry(): { packageRoot: string; entryPath: string } {
  const packageRoot = createTemporaryDirectory("repo");
  writeFileSync(
    path.join(packageRoot, "package.json"),
    JSON.stringify({ name: "milestack", version: "9.9.9" }),
    "utf8",
  );
  const entryPath = path.join(packageRoot, "dist", "index.js");
  writeFileAt(entryPath);
  return { packageRoot, entryPath };
}

function createPnpmGlobalEntry(): string {
  const root = createTemporaryDirectory("pnpm");
  const packageRoot = path.join(root, "global", "5", "node_modules", "milestack");
  writeFileAt(path.join(packageRoot, "dist", "index.js"));
  writeFileSync(
    path.join(packageRoot, "package.json"),
    JSON.stringify({ name: "milestack" }),
    "utf8",
  );
  return path.join(packageRoot, "dist", "index.js");
}

function createNpxEntry(): string {
  const root = createTemporaryDirectory("npx");
  const packageRoot = path.join(root, ".npm", "_npx", "a1b2c3", "node_modules", "milestack");
  writeFileAt(path.join(packageRoot, "dist", "index.js"));
  writeFileSync(
    path.join(packageRoot, "package.json"),
    JSON.stringify({ name: "milestack" }),
    "utf8",
  );
  return path.join(packageRoot, "dist", "index.js");
}

const staleGeneratedContent =
  "<!-- Generated by MileStack milestack init; source: MileStack 0.1.0; version: 0.1.0. -->\n# Old generated body\n";

function createInitializedProject(): { projectRoot: string; instructionsPath: string } {
  const projectRoot = createTemporaryDirectory("project");
  const milestackDirectory = path.join(projectRoot, ".milestack");
  mkdirSync(milestackDirectory, { recursive: true });
  writeFileSync(path.join(milestackDirectory, "milestack.db"), "", "utf8");
  const instructionsPath = path.join(projectRoot, projectAgentInstructionsPath);
  writeFileSync(instructionsPath, staleGeneratedContent, "utf8");
  return { projectRoot, instructionsPath };
}

function createUninitializedProject(): string {
  return createTemporaryDirectory("empty");
}

type NpmFakeOptions = {
  globalPrefix?: string | undefined;
  latest?: string | undefined;
  queryError?: string | undefined;
  installFails?: boolean;
  installError?: string | undefined;
};

type NpmFake = {
  calls: string[][];
  dependencies: (entryPath: string) => UpdateDependencies;
};

function createNpmFake(options: NpmFakeOptions): NpmFake {
  const calls: string[][] = [];
  const runNpm = (args: readonly string[]): NpmCommandResult => {
    calls.push([...args]);
    if (args[0] === "prefix") {
      return options.globalPrefix === undefined
        ? { status: 1, stdout: "", stderr: "npm: not found" }
        : { status: 0, stdout: `${options.globalPrefix}\n`, stderr: "" };
    }
    if (args[0] === "view") {
      return options.latest === undefined
        ? { status: 1, stdout: "", stderr: options.queryError ?? "network error" }
        : { status: 0, stdout: `${options.latest}\n`, stderr: "" };
    }
    if (args[0] === "install") {
      return options.installFails === true
        ? { status: 1, stdout: "", stderr: options.installError ?? "install failed" }
        : { status: 0, stdout: "added 1 package\n", stderr: "" };
    }
    return { status: 1, stdout: "", stderr: `unexpected npm call: ${args.join(" ")}` };
  };
  return {
    calls,
    dependencies: (entryPath: string) => ({ resolveEntryPath: () => entryPath, runNpm }),
  };
}

function npmCallsStartingWith(fake: NpmFake, command: string): string[][] {
  return fake.calls.filter((call) => call[0] === command);
}

describe("milestack update: npm global self-update", () => {
  it("upgrades a newer npm global install and refreshes the project file only", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const rootAgentsPath = path.join(projectRoot, "AGENTS.md");
    const clientConfigPath = path.join(projectRoot, "opencode.json");
    const gitignorePath = path.join(projectRoot, ".gitignore");
    writeFileSync(rootAgentsPath, "# Existing project instructions\n", "utf8");
    writeFileSync(clientConfigPath, '{"mcp":{"other":{"command":"keep"}}}\n', "utf8");
    writeFileSync(gitignorePath, "dist/\n", "utf8");
    const fake = createNpmFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain(`当前版本：${runtimeVersion}`);
    expect(stdout).toContain("最新版本：9.9.9");
    expect(stdout).toContain("npm install --global milestack@latest");
    expect(stdout).toContain(`升级完成：${runtimeVersion} -> 9.9.9`);
    expect(stdout).toContain("milestack -v");
    expect(stdout).toContain("MCP");
    expect(stdout).toContain("serve");
    expect(stdout).toContain(`已刷新 ${instructionsPath}`);
    expect(capture.stderr).toEqual([]);

    expect(npmCallsStartingWith(fake, "install")).toEqual([
      ["install", "--global", "milestack@latest"],
    ]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
    expect(readFileSync(rootAgentsPath, "utf8")).toBe("# Existing project instructions\n");
    expect(readFileSync(clientConfigPath, "utf8")).toBe('{"mcp":{"other":{"command":"keep"}}}\n');
    expect(readFileSync(gitignorePath, "utf8")).toBe("dist/\n");
  });

  it("reports already-latest, skips the installer, and still refreshes", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({ globalPrefix: prefix, latest: runtimeVersion });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    expect(capture.stdout.join("")).toContain("已是最新版本，未执行安装");
    expect(capture.stderr).toEqual([]);
    expect(npmCallsStartingWith(fake, "install")).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("keeps the installed package unchanged when the install command fails", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({
      globalPrefix: prefix,
      latest: "9.9.9",
      installFails: true,
      installError: "EACCES permission denied",
    });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("安装失败：EACCES permission denied");
    expect(stdout).toContain(`已刷新 ${instructionsPath}`);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("reports a registry query failure without installing and still refreshes", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({
      globalPrefix: prefix,
      queryError: "ENOTFOUND registry.npmjs.org",
    });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("查询最新版本失败：ENOTFOUND registry.npmjs.org");
    expect(npmCallsStartingWith(fake, "install")).toEqual([]);
    expect(stdout).toContain(`已刷新 ${instructionsPath}`);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("skips the project refresh for uninitialized directories without creating .milestack", async () => {
    for (const latest of ["9.9.9", runtimeVersion]) {
      const { prefix, entryPath } = createNpmGlobalEntry();
      const projectRoot = createUninitializedProject();
      const fake = createNpmFake({ globalPrefix: prefix, latest });
      const capture = outputCapture();

      const exitCode = await runCli(
        ["update", "--project", projectRoot],
        capture.output,
        fake.dependencies(entryPath),
      );

      expect(exitCode).toBe(0);
      expect(capture.stdout.join("")).toContain("跳过");
      expect(existsSync(path.join(projectRoot, ".milestack"))).toBe(false);
    }
  });

  it("reports both the install result and the refresh failure when writing fails", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    rmSync(instructionsPath);
    mkdirSync(instructionsPath);
    const fake = createNpmFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("升级完成");
    expect(stdout).toContain("刷新生成文件失败");
  });

  it("writes the running CLI version into the generated header", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();
    vi.resetModules();
    vi.doMock("../src/server/runtime-version.js", () => ({ runtimeVersion: "9.9.9" }));
    try {
      const { runCli: runCliWithVersion } = await import("../src/cli/command.js");

      const exitCode = await runCliWithVersion(
        ["update", "--project", projectRoot],
        capture.output,
        fake.dependencies(entryPath),
      );

      expect(exitCode).toBe(0);
      const content = readFileSync(instructionsPath, "utf8");
      expect(content).toContain("source: MileStack 9.9.9; version: 9.9.9");
      expect(content).not.toContain("source: MileStack 0.1.0; version: 0.1.0");
    } finally {
      vi.doUnmock("../src/server/runtime-version.js");
      vi.resetModules();
    }
  });
});

describe("milestack update --check", () => {
  it("reports an available update and an inconsistent generated file without writing", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({ globalPrefix: prefix, latest: "9.9.9" });
    const before = readFileSync(instructionsPath, "utf8");
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--check", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain(`当前版本：${runtimeVersion}`);
    expect(stdout).toContain("最新版本：9.9.9");
    expect(stdout).toContain("--check 未执行安装");
    expect(stdout).toContain("生成文件与当前 CLI 的完整生成结果不一致");
    expect(npmCallsStartingWith(fake, "install")).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(before);
  });

  it("reports a consistent generated file", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    writeFileSync(instructionsPath, formatProjectAgentInstructions(runtimeVersion), "utf8");
    const fake = createNpmFake({ globalPrefix: prefix, latest: runtimeVersion });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--check", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("生成文件与当前 CLI 的完整生成结果一致");
    expect(stdout).not.toContain("不一致");
  });

  it("fails when the registry query fails", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({ globalPrefix: prefix, queryError: "EHOSTUNREACH" });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--check", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    expect(capture.stdout.join("")).toContain("查询最新版本失败：EHOSTUNREACH");
    expect(npmCallsStartingWith(fake, "install")).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(staleGeneratedContent);
  });

  it("skips uninitialized directories without creating .milestack", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const projectRoot = createUninitializedProject();
    const fake = createNpmFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--check", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    expect(capture.stdout.join("")).toContain("跳过");
    expect(existsSync(path.join(projectRoot, ".milestack"))).toBe(false);
  });
});

describe("milestack update: source repository and non-npm installs", () => {
  it("does not install or query the registry for a source repository entry", async () => {
    const { packageRoot, entryPath } = createSourceRepoEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({});
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain(`入口：${entryPath}`);
    expect(stdout).toContain("pnpm link --global");
    expect(stdout).toContain(`pnpm build（仓库：${packageRoot}）`);
    expect(npmCallsStartingWith(fake, "install")).toEqual([]);
    expect(npmCallsStartingWith(fake, "view")).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("reports a source repository entry under --check without writing", async () => {
    const { packageRoot, entryPath } = createSourceRepoEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({});
    const before = readFileSync(instructionsPath, "utf8");
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--check", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain(`入口：${entryPath}`);
    expect(stdout).toContain(`pnpm build（仓库：${packageRoot}）`);
    expect(stdout).toContain("生成文件与当前 CLI 的完整生成结果不一致");
    expect(npmCallsStartingWith(fake, "install")).toEqual([]);
    expect(npmCallsStartingWith(fake, "view")).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(before);
  });

  it("does not install or query the registry for a pnpm global entry", async () => {
    const entryPath = createPnpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({});
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("pnpm 全局安装");
    expect(stdout).toContain("沿用原来的 pnpm 方式自行升级");
    expect(stdout).toContain("不会改跑 npm");
    expect(npmCallsStartingWith(fake, "install")).toEqual([]);
    expect(npmCallsStartingWith(fake, "view")).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("does not install for an npx entry and prints the manual command", async () => {
    const entryPath = createNpxEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createNpmFake({});
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("npx 临时副本");
    expect(stdout).toContain("npm install --global milestack@latest");
    expect(stdout).toContain("本次未执行");
    expect(npmCallsStartingWith(fake, "install")).toEqual([]);
    expect(npmCallsStartingWith(fake, "view")).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("does not create .milestack for an uninitialized source repository project", async () => {
    const { entryPath } = createSourceRepoEntry();
    const projectRoot = createUninitializedProject();
    const fake = createNpmFake({});
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    expect(capture.stdout.join("")).toContain("跳过");
    expect(existsSync(path.join(projectRoot, ".milestack"))).toBe(false);
  });

  it("names the npm executable for Windows", () => {
    expect(npmExecutable("win32")).toBe("npm.cmd");
    expect(npmExecutable("darwin")).toBe("npm");
    expect(npmExecutable("linux")).toBe("npm");
  });
});

describe("milestack update: argument handling", () => {
  it("lists the update command and --check in the help text", () => {
    expect(helpText).toContain("update");
    expect(helpText).toContain("--check");
  });

  it("rejects --check on commands other than update", async () => {
    const capture = outputCapture();

    const exitCode = await runCli(["status", "--check"], capture.output);

    expect(exitCode).toBe(1);
    expect(capture.stderr.join("")).toContain(
      "--check is only supported for the update command.",
    );
  });
});
