// Plain output with a frozen clock, so step lines are deterministic.
const plainDisplay: StepDisplay = {
  interactive: false,
  color: false,
  now: () => 0,
  tickMs: 10,
  columns: () => 80,
};

type CommandFakeOptions = {
  globalPrefix?: string | undefined;
  latest?: string | undefined;
  queryError?: string | undefined;
  installFails?: boolean;
  installError?: string | undefined;
  // Holds the installer open, then reports (before succeeding or failing) so a
  // test can look at what was already printed.
  queryDelayMs?: number;
  onQueryDelayElapsed?: () => void;
  installDelayMs?: number;
  onInstallDelayElapsed?: () => void;
  // Runs when the installer succeeds, to put the new version on disk.
  onInstall?: () => void;
  // What the newly installed CLI writes when asked to refresh. Left unset, the
  // refresh child does nothing, as if it failed.
  childWrites?: { instructionsPath: string; version: string };
};

type CommandFake = {
  calls: CommandInvocation[];
  dependencies: (entryPath: string, display?: StepDisplay) => UpdateDependencies;
};

function createCommandFake(options: CommandFakeOptions): CommandFake {
  const calls: CommandInvocation[] = [];
  const runCommand = async (invocation: CommandInvocation): Promise<CommandResult> => {
    calls.push({
      command: invocation.command,
      args: [...invocation.args],
      ...(invocation.cwd !== undefined ? { cwd: invocation.cwd } : {}),
    });
    const subcommand = invocation.args[0];
    if (subcommand === "prefix") {
      return options.globalPrefix === undefined
        ? { status: 1, stdout: "", stderr: "npm: not found" }
        : { status: 0, stdout: `${options.globalPrefix}\n`, stderr: "" };
    }
    if (subcommand === "view") {
      if (options.queryDelayMs !== undefined) {
        await new Promise((resolve) => setTimeout(resolve, options.queryDelayMs));
        options.onQueryDelayElapsed?.();
      }
      return options.latest === undefined
        ? { status: 1, stdout: "", stderr: options.queryError ?? "network error" }
        : { status: 0, stdout: `${options.latest}\n`, stderr: "" };
    }
    if (subcommand === "install" || subcommand === "update") {
      if (options.installDelayMs !== undefined) {
        await new Promise((resolve) => setTimeout(resolve, options.installDelayMs));
        options.onInstallDelayElapsed?.();
      }
      if (options.installFails === true) {
        return { status: 1, stdout: "", stderr: options.installError ?? "install failed" };
      }
      options.onInstall?.();
      return { status: 0, stdout: "updated 1 package\n", stderr: "" };
    }
    if (invocation.command === process.execPath) {
      if (options.childWrites === undefined) {
        return { status: 1, stdout: "", stderr: "refresh child failed" };
      }
      writeFileSync(
        options.childWrites.instructionsPath,
        formatProjectAgentInstructions(options.childWrites.version),
        "utf8",
      );
      return { status: 0, stdout: "", stderr: "" };
    }
    return {
      status: 1,
      stdout: "",
      stderr: `unexpected command: ${invocation.command} ${invocation.args.join(" ")}`,
    };
  };
  return {
    calls,
    dependencies: (entryPath: string, display: StepDisplay = plainDisplay) => ({
      resolveEntryPath: () => entryPath,
      runCommand,
      display,
    }),
  };
}

function writeInstalledPackage(packageRoot: string, version: string): string {
  const entryPath = path.join(packageRoot, "dist", "index.js");
  writeFileAt(entryPath);
  writeFileSync(
    path.join(packageRoot, "package.json"),
    JSON.stringify({ name: "milestack", version, bin: { milestack: "dist/index.js" } }),
    "utf8",
  );
  return entryPath;
}

function refreshCalls(fake: CommandFake): CommandInvocation[] {
  return fake.calls.filter((call) => call.command === process.execPath);
}

function installerCalls(fake: CommandFake): CommandInvocation[] {
  return fake.calls.filter(
    (call) => call.args[0] === "install" || call.args[0] === "update",
  );
}

function queryCalls(fake: CommandFake): CommandInvocation[] {
  return fake.calls.filter((call) => call.args[0] === "view");
}

describe("milestack update: npm global self-update", () => {
  it("upgrades a newer npm global install and refreshes the project file only", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const rootAgentsPath = path.join(projectRoot, "AGENTS.md");
    const clientConfigPath = path.join(projectRoot, "opencode.json");
    const gitignorePath = path.join(projectRoot, ".gitignore");
    writeFileSync(rootAgentsPath, "# Existing project instructions\n", "utf8");
    writeFileSync(clientConfigPath, '{"mcp":{"other":{"command":"keep"}}}\n', "utf8");
    writeFileSync(gitignorePath, "dist/\n", "utf8");
    const packageRoot = path.join(prefix, "lib", "node_modules", "milestack");
    const fake = createCommandFake({
      globalPrefix: prefix,
      latest: "9.9.9",
      onInstall: () => writeInstalledPackage(packageRoot, "9.9.9"),
      childWrites: { instructionsPath, version: "9.9.9" },
    });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain(`MileStack update  ${runtimeVersion} → 9.9.9`);
    expect(stdout).toContain("✔ 检测安装方式");
    expect(stdout).toContain("npm 全局安装");
    expect(stdout).toContain(`入口：${entryPath}`);
    expect(stdout).toContain("✔ 查询最新版本");
    expect(stdout).toContain("9.9.9 可用");
    expect(stdout).toContain("✔ 安装 milestack@9.9.9");
    expect(stdout).toContain("执行：npm install --global milestack@latest");
    expect(stdout).toContain("✔ 刷新项目生成文件");
    expect(stdout).toContain(`${instructionsPath}（由新版本 9.9.9 生成）`);
    expect(stdout).toContain("✓ 已升级到 9.9.9 · 请重启 MCP 客户端和 milestack serve");
    expect(stdout).toContain("milestack -v");
    expect(stdout.indexOf("检测安装方式")).toBeLessThan(stdout.indexOf("查询最新版本"));
    expect(stdout.indexOf("查询最新版本")).toBeLessThan(stdout.indexOf("安装 milestack@9.9.9"));
    expect(stdout.indexOf("安装 milestack@9.9.9")).toBeLessThan(stdout.indexOf("刷新项目生成文件"));
    expect(capture.stderr).toEqual([]);

    expect(installerCalls(fake)).toEqual([
      { command: "npm", args: ["install", "--global", "milestack@latest"] },
    ]);
    expect(refreshCalls(fake)).toEqual([
      {
        command: process.execPath,
        args: [realpathSync(entryPath), "update", "--project", projectRoot],
      },
    ]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(formatProjectAgentInstructions("9.9.9"));
    expect(readFileSync(rootAgentsPath, "utf8")).toBe("# Existing project instructions\n");
    expect(readFileSync(clientConfigPath, "utf8")).toBe('{"mcp":{"other":{"command":"keep"}}}\n');
    expect(readFileSync(gitignorePath, "utf8")).toBe("dist/\n");
  });

  it("reports already-latest, skips the installer, and still refreshes", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({ globalPrefix: prefix, latest: runtimeVersion });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    expect(capture.stdout.join("")).toContain("已是最新版本，未执行安装");
    expect(capture.stderr).toEqual([]);
    expect(installerCalls(fake)).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("keeps the installed package unchanged and stops when the install command fails", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({
      globalPrefix: prefix,
      latest: "9.9.9",
      installFails: true,
      installError: "EACCES permission denied",
    });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("✖ 安装 milestack@9.9.9");
    expect(stdout).toContain("EACCES permission denied");
    expect(stdout).toContain("手动执行：npm install --global milestack@latest");
    expect(stdout).not.toContain("刷新项目生成文件");
    expect(stdout).not.toContain("已升级到");
    expect(refreshCalls(fake)).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(staleGeneratedContent);
  });

  it("reports a registry query failure without installing or refreshing", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({
      globalPrefix: prefix,
      queryError: "ENOTFOUND registry.npmjs.org",
    });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("✖ 查询最新版本");
    expect(stdout).toContain("ENOTFOUND registry.npmjs.org");
    expect(stdout).toContain("手动执行：npm view milestack version");
    expect(stdout).not.toContain("刷新项目生成文件");
    expect(installerCalls(fake)).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(staleGeneratedContent);
  });

  it("skips the project refresh for uninitialized directories without creating .milestack", async () => {
    for (const latest of ["9.9.9", runtimeVersion]) {
      const { prefix, entryPath } = createNpmGlobalEntry();
      const projectRoot = createUninitializedProject();
      const fake = createCommandFake({ globalPrefix: prefix, latest });
      const capture = outputCapture();

      const exitCode = await runCli(
        ["update", "--project", projectRoot],
        capture.output,
        fake.dependencies(entryPath),
      );

      expect(exitCode).toBe(0);
      expect(capture.stdout.join("")).toContain("跳过");
      expect(existsSync(path.join(projectRoot, ".milestack"))).toBe(false);
    }
  });

  it("does not report a refresh when the new CLI fails to refresh", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const packageRoot = path.join(prefix, "lib", "node_modules", "milestack");
    const fake = createCommandFake({
      globalPrefix: prefix,
      latest: "9.9.9",
      onInstall: () => writeInstalledPackage(packageRoot, "9.9.9"),
    });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("已安装 9.9.9，但项目生成文件未刷新");
    expect(stdout).not.toContain("已升级到");
    expect(stdout).not.toContain("已刷新");
    expect(stdout).toContain("refresh child failed");
    expect(stdout).toContain("请再运行一次 milestack update");
    expect(readFileSync(instructionsPath, "utf8")).toBe(staleGeneratedContent);
  });

  it("does not trust or run a located CLI that is still older than the installed version", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const packageRoot = path.join(prefix, "lib", "node_modules", "milestack");
    // The installer exits 0 but the package on disk is still 0.1.0, and the
    // generated file already carries that version.
    writeInstalledPackage(packageRoot, "0.1.0");
    const fake = createCommandFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).not.toContain("已刷新");
    expect(stdout).toContain("请再运行一次 milestack update");
    expect(refreshCalls(fake)).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(staleGeneratedContent);
  });

  it("does not report a refresh when the new CLI cannot be located after install", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("无法确定新安装的 CLI");
    expect(stdout).not.toContain("已刷新");
    expect(stdout).toContain("请再运行一次 milestack update");
    expect(refreshCalls(fake)).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(staleGeneratedContent);
  });

  it("writes the running CLI version into the generated header", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();
    vi.resetModules();
    vi.doMock("../src/server/runtime-version.js", () => ({ runtimeVersion: "9.9.9" }));
    try {
      const { runCli: runCliWithVersion } = await import("../src/cli/command.js");

      const exitCode = await runCliWithVersion(
        ["update", "--project", projectRoot],
        capture.output,
        fake.dependencies(entryPath),
      );

      expect(exitCode).toBe(0);
      const content = readFileSync(instructionsPath, "utf8");
      expect(content).toContain("source: MileStack 9.9.9; version: 9.9.9");
      expect(content).not.toContain("source: MileStack 0.1.0; version: 0.1.0");
    } finally {
      vi.doUnmock("../src/server/runtime-version.js");
      vi.resetModules();
    }
  });
});

