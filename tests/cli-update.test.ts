const temporaryPaths: string[] = [];

function createTemporaryDirectory(prefix: string): string {
  const directory = path.join(os.tmpdir(), `milestack-update-${prefix}-${randomUUID()}`);
  mkdirSync(directory, { recursive: true });
  temporaryPaths.push(directory);
  return directory;
}

afterEach(() => {
  for (const target of temporaryPaths.splice(0)) {
    rmSync(target, { recursive: true, force: true });
  }
});

function outputCapture() {
  const stdout: string[] = [];
  const stderr: string[] = [];
  return {
    stdout,
    stderr,
    output: {
      writeStdout: (message: string) => stdout.push(message),
      writeStderr: (message: string) => stderr.push(message),
    },
  };
}

function writeFileAt(filePath: string, contents = "// fake CLI entry\n"): void {
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(filePath, contents, "utf8");
}

function createNpmGlobalEntry(): { prefix: string; entryPath: string } {
  const prefix = createTemporaryDirectory("prefix");
  const entryPath = path.join(prefix, "lib", "node_modules", "milestack", "dist", "index.js");
  writeFileAt(entryPath);
  return { prefix, entryPath };
}

function createSourceRepoEntry(): { packageRoot: string; entryPath: string } {
  const packageRoot = createTemporaryDirectory("repo");
  writeFileSync(
    path.join(packageRoot, "package.json"),
    JSON.stringify({ name: "milestack", version: "9.9.9" }),
    "utf8",
  );
  const entryPath = path.join(packageRoot, "dist", "index.js");
  writeFileAt(entryPath);
  return { packageRoot, entryPath };
}

function createPnpmGlobalEntry(): string {
  const root = createTemporaryDirectory("pnpm");
  const globalRoot = path.join(root, "global", "5");
  const packageRoot = path.join(globalRoot, "node_modules", "milestack");
  writeFileAt(path.join(packageRoot, "dist", "index.js"));
  writeFileSync(
    path.join(packageRoot, "package.json"),
    JSON.stringify({ name: "milestack" }),
    "utf8",
  );
  // A pnpm global directory can also carry its own dependency manifest; the
  // entry must still be classified as a pnpm global install, not a project.
  writeFileSync(
    path.join(globalRoot, "package.json"),
    JSON.stringify({ dependencies: { milestack: "^0.1.0" } }),
    "utf8",
  );
  return path.join(packageRoot, "dist", "index.js");
}

function createNpxEntry(): string {
  const root = createTemporaryDirectory("npx");
  const npxRoot = path.join(root, ".npm", "_npx", "a1b2c3");
  const packageRoot = path.join(npxRoot, "node_modules", "milestack");
  writeFileAt(path.join(packageRoot, "dist", "index.js"));
  writeFileSync(
    path.join(packageRoot, "package.json"),
    JSON.stringify({ name: "milestack" }),
    "utf8",
  );
  // The npx cache directory also declares the package; it must not be treated
  // as a user project.
  writeFileSync(
    path.join(npxRoot, "package.json"),
    JSON.stringify({ dependencies: { milestack: "^0.1.0" } }),
    "utf8",
  );
  return path.join(packageRoot, "dist", "index.js");
}

const staleGeneratedContent =
  "<!-- Generated by MileStack milestack init; source: MileStack 0.1.0; version: 0.1.0. -->\n# Old generated body\n";

function initializeProjectDirectory(
  projectRoot: string,
): { projectRoot: string; instructionsPath: string } {
  const milestackDirectory = path.join(projectRoot, ".milestack");
  mkdirSync(milestackDirectory, { recursive: true });
  writeFileSync(path.join(milestackDirectory, "milestack.db"), "", "utf8");
  const instructionsPath = path.join(projectRoot, projectAgentInstructionsPath);
  writeFileSync(instructionsPath, staleGeneratedContent, "utf8");
  return { projectRoot, instructionsPath };
}

function createInitializedProject(): { projectRoot: string; instructionsPath: string } {
  return initializeProjectDirectory(createTemporaryDirectory("project"));
}

function createUninitializedProject(): string {
  return createTemporaryDirectory("empty");
}

type ProjectLocalFixture = {
  projectRoot: string;
  entryPath: string;
  packageJsonPath: string;
  packageJsonContent: string;
};

function createNpmProjectLocalEntry(options: {
  dependencyField: "dependencies" | "devDependencies";
  lockfileNames: readonly string[];
}): ProjectLocalFixture {
  const projectRoot = createTemporaryDirectory("npm-project");
  const packageJsonContent = `${JSON.stringify(
    { name: "consumer", [options.dependencyField]: { milestack: "^0.1.0" } },
    null,
    2,
  )}\n`;
  const packageJsonPath = path.join(projectRoot, "package.json");
  writeFileSync(packageJsonPath, packageJsonContent, "utf8");
  for (const lockfileName of options.lockfileNames) {
    writeFileSync(path.join(projectRoot, lockfileName), "lockfile\n", "utf8");
  }
  const packageRoot = path.join(projectRoot, "node_modules", "milestack");
  writeFileAt(path.join(packageRoot, "dist", "index.js"));
  writeFileSync(
    path.join(packageRoot, "package.json"),
    JSON.stringify({ name: "milestack" }),
    "utf8",
  );
  return {
    projectRoot,
    entryPath: path.join(packageRoot, "dist", "index.js"),
    packageJsonPath,
    packageJsonContent,
  };
}

