type CommandFakeOptions = {
  globalPrefix?: string | undefined;
  latest?: string | undefined;
  queryError?: string | undefined;
  installFails?: boolean;
  installError?: string | undefined;
};

type CommandFake = {
  calls: CommandInvocation[];
  dependencies: (entryPath: string) => UpdateDependencies;
};

function createCommandFake(options: CommandFakeOptions): CommandFake {
  const calls: CommandInvocation[] = [];
  const runCommand = (invocation: CommandInvocation): CommandResult => {
    calls.push({
      command: invocation.command,
      args: [...invocation.args],
      ...(invocation.cwd !== undefined ? { cwd: invocation.cwd } : {}),
    });
    const subcommand = invocation.args[0];
    if (subcommand === "prefix") {
      return options.globalPrefix === undefined
        ? { status: 1, stdout: "", stderr: "npm: not found" }
        : { status: 0, stdout: `${options.globalPrefix}\n`, stderr: "" };
    }
    if (subcommand === "view") {
      return options.latest === undefined
        ? { status: 1, stdout: "", stderr: options.queryError ?? "network error" }
        : { status: 0, stdout: `${options.latest}\n`, stderr: "" };
    }
    if (subcommand === "install" || subcommand === "update") {
      return options.installFails === true
        ? { status: 1, stdout: "", stderr: options.installError ?? "install failed" }
        : { status: 0, stdout: "updated 1 package\n", stderr: "" };
    }
    return {
      status: 1,
      stdout: "",
      stderr: `unexpected command: ${invocation.command} ${invocation.args.join(" ")}`,
    };
  };
  return {
    calls,
    dependencies: (entryPath: string) => ({ resolveEntryPath: () => entryPath, runCommand }),
  };
}

function installerCalls(fake: CommandFake): CommandInvocation[] {
  return fake.calls.filter(
    (call) => call.args[0] === "install" || call.args[0] === "update",
  );
}

function queryCalls(fake: CommandFake): CommandInvocation[] {
  return fake.calls.filter((call) => call.args[0] === "view");
}

describe("milestack update: npm global self-update", () => {
  it("upgrades a newer npm global install and refreshes the project file only", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const rootAgentsPath = path.join(projectRoot, "AGENTS.md");
    const clientConfigPath = path.join(projectRoot, "opencode.json");
    const gitignorePath = path.join(projectRoot, ".gitignore");
    writeFileSync(rootAgentsPath, "# Existing project instructions\n", "utf8");
    writeFileSync(clientConfigPath, '{"mcp":{"other":{"command":"keep"}}}\n', "utf8");
    writeFileSync(gitignorePath, "dist/\n", "utf8");
    const fake = createCommandFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain(`当前版本：${runtimeVersion}`);
    expect(stdout).toContain("最新版本：9.9.9");
    expect(stdout).toContain("npm install --global milestack@latest");
    expect(stdout).toContain(`升级完成：${runtimeVersion} -> 9.9.9`);
    expect(stdout).toContain("milestack -v");
    expect(stdout).toContain("MCP");
    expect(stdout).toContain("serve");
    expect(stdout).toContain(`已刷新 ${instructionsPath}`);
    expect(capture.stderr).toEqual([]);

    expect(installerCalls(fake)).toEqual([
      { command: "npm", args: ["install", "--global", "milestack@latest"] },
    ]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
    expect(readFileSync(rootAgentsPath, "utf8")).toBe("# Existing project instructions\n");
    expect(readFileSync(clientConfigPath, "utf8")).toBe('{"mcp":{"other":{"command":"keep"}}}\n');
    expect(readFileSync(gitignorePath, "utf8")).toBe("dist/\n");
  });

  it("reports already-latest, skips the installer, and still refreshes", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({ globalPrefix: prefix, latest: runtimeVersion });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(0);
    expect(capture.stdout.join("")).toContain("已是最新版本，未执行安装");
    expect(capture.stderr).toEqual([]);
    expect(installerCalls(fake)).toEqual([]);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("keeps the installed package unchanged when the install command fails", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({
      globalPrefix: prefix,
      latest: "9.9.9",
      installFails: true,
      installError: "EACCES permission denied",
    });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("安装失败：EACCES permission denied");
    expect(stdout).toContain(`已刷新 ${instructionsPath}`);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("reports a registry query failure without installing and still refreshes", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({
      globalPrefix: prefix,
      queryError: "ENOTFOUND registry.npmjs.org",
    });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("查询最新版本失败：ENOTFOUND registry.npmjs.org");
    expect(installerCalls(fake)).toEqual([]);
    expect(stdout).toContain(`已刷新 ${instructionsPath}`);
    expect(readFileSync(instructionsPath, "utf8")).toBe(
      formatProjectAgentInstructions(runtimeVersion),
    );
  });

  it("skips the project refresh for uninitialized directories without creating .milestack", async () => {
    for (const latest of ["9.9.9", runtimeVersion]) {
      const { prefix, entryPath } = createNpmGlobalEntry();
      const projectRoot = createUninitializedProject();
      const fake = createCommandFake({ globalPrefix: prefix, latest });
      const capture = outputCapture();

      const exitCode = await runCli(
        ["update", "--project", projectRoot],
        capture.output,
        fake.dependencies(entryPath),
      );

      expect(exitCode).toBe(0);
      expect(capture.stdout.join("")).toContain("跳过");
      expect(existsSync(path.join(projectRoot, ".milestack"))).toBe(false);
    }
  });

  it("reports both the install result and the refresh failure when writing fails", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    rmSync(instructionsPath);
    mkdirSync(instructionsPath);
    const fake = createCommandFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();

    const exitCode = await runCli(
      ["update", "--project", projectRoot],
      capture.output,
      fake.dependencies(entryPath),
    );

    expect(exitCode).toBe(1);
    const stdout = capture.stdout.join("");
    expect(stdout).toContain("升级完成");
    expect(stdout).toContain("刷新生成文件失败");
  });

  it("writes the running CLI version into the generated header", async () => {
    const { prefix, entryPath } = createNpmGlobalEntry();
    const { projectRoot, instructionsPath } = createInitializedProject();
    const fake = createCommandFake({ globalPrefix: prefix, latest: "9.9.9" });
    const capture = outputCapture();
    vi.resetModules();
    vi.doMock("../src/server/runtime-version.js", () => ({ runtimeVersion: "9.9.9" }));
    try {
      const { runCli: runCliWithVersion } = await import("../src/cli/command.js");

      const exitCode = await runCliWithVersion(
        ["update", "--project", projectRoot],
        capture.output,
        fake.dependencies(entryPath),
      );

      expect(exitCode).toBe(0);
      const content = readFileSync(instructionsPath, "utf8");
      expect(content).toContain("source: MileStack 9.9.9; version: 9.9.9");
      expect(content).not.toContain("source: MileStack 0.1.0; version: 0.1.0");
    } finally {
      vi.doUnmock("../src/server/runtime-version.js");
      vi.resetModules();
    }
  });
});

