import { readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

import {
  formatProjectAgentInstructions,
  projectAgentInstructionsPath,
} from "../core/agent-instructions.js";
import { compareSemver, parseSemver } from "../update/version-check.js";

export function readGeneratedHeaderLine(instructionsPath: string): string {
  try {
    return readFileSync(instructionsPath, "utf8").split("\n", 1)[0] ?? "";
  } catch {
    return "";
  }
}

const generatedHeaderPattern =
  /^<!-- Generated by MileStack milestack init; source: MileStack [^;]+; version: (.+)\. -->$/;

// The version the generator recorded, or undefined when the line is not an
// intact MileStack generation marker.
function parseGeneratedVersion(headerLine: string): string | undefined {
  const version = generatedHeaderPattern.exec(headerLine.trimEnd())?.[1];
  return version !== undefined && parseSemver(version) !== undefined ? version : undefined;
}

// Writes beside the target and renames, so a concurrent reader or a second
// starting process never sees a half-written file.
export function writeFileAtomically(target: string, content: string): void {
  const temporaryPath = `${target}.${process.pid}.tmp`;
  try {
    writeFileSync(temporaryPath, content, "utf8");
    renameSync(temporaryPath, target);
  } catch (error) {
    rmSync(temporaryPath, { force: true });
    throw error;
  }
}

export type InstructionsRefreshResult =
  | { kind: "unchanged" }
  | { kind: "refreshed"; from: string; to: string; instructionsPath: string }
  | { kind: "not-generated"; instructionsPath: string }
  | { kind: "failed"; reason: string; instructionsPath: string };

// Brings an existing generated file up to the running version. It only moves
// forward: an equal or newer file, an unknown running version, and a file
// without an intact generation marker are never rewritten.
export function refreshStaleInstructions(
  projectRoot: string,
  currentVersion: string,
  writeFile: (target: string, content: string) => void = writeFileAtomically,
): InstructionsRefreshResult {
  if (parseSemver(currentVersion) === undefined) {
    return { kind: "unchanged" };
  }
  const instructionsPath = path.join(projectRoot, projectAgentInstructionsPath);
  const fileVersion = parseGeneratedVersion(readGeneratedHeaderLine(instructionsPath));
  if (fileVersion === undefined) {
    return { kind: "not-generated", instructionsPath };
  }
  const comparison = compareSemver(currentVersion, fileVersion);
  if (comparison === undefined || comparison <= 0) {
    return { kind: "unchanged" };
  }
  try {
    writeFile(instructionsPath, formatProjectAgentInstructions(currentVersion));
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    return { kind: "failed", reason, instructionsPath };
  }
  return { kind: "refreshed", from: fileVersion, to: currentVersion, instructionsPath };
}
