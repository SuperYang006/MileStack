    "- .milestack/agent-instructions.md 不会自动成为仓库源码的嵌套 Agent 规范；嵌套 AGENTS.md 也不会因 milestack init 自动约束仓库源码。需要团队共享的长期规则、架构和协议仍写在受版本控制的根 AGENTS.md 或长期文档中。",
